# ==========================================================
# RAG
# ==========================================================

def build_rag_prompt(
    question: str,
    context: str
) -> str:
    """
    RAG问答 Prompt
    """

    return f"""
你是一名专业HR助手。

请严格依据下面提供的知识回答用户问题。

要求：

1. 只能依据知识回答。
2. 不允许自行编造。
3. 如果知识不足，请回答：
知识库中暂无相关信息。
4. 回答尽量简洁。
5. 如果知识能够直接回答，请不要解释。

====================

知识：

{context}

====================

问题：

{question}

回答：
""".strip()


# ==========================================================
# Resume
# ==========================================================

def build_resume_prompt(
    resume_text: str
) -> str:
    """
    简历解析 Prompt
    """

    return f"""
你是一名专业HR。

请从下面简历中提取信息。

返回JSON。

简历：

{resume_text}
""".strip()


# ==========================================================
# JD
# ==========================================================

def build_jd_prompt(
    jd: str,
    resume: str
):
    """
    JD匹配
    """

    return f"""
请根据岗位要求分析候选人匹配度。

岗位：

{jd}

====================

简历：

{resume}

返回JSON。
""".strip()


# ==========================================================
# Talent
# ==========================================================

def build_talent_prompt(
    keyword: str
):
    """
    人才推荐Prompt
    """

    return f"""
请根据下面的人才信息推荐候选人。

关键词：

{keyword}
""".strip()


